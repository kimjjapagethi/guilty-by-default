import json, re, sys

def split(text, maxlen=88):
    toks = re.split(r'(?<=[.?!])\s+', text.strip())
    out, cur = [], ''
    for t in toks:
        if not cur: cur = t
        elif len(cur) + 1 + len(t) <= maxlen: cur += ' ' + t
        else: out.append(cur); cur = t
    if cur: out.append(cur)
    return out

def L(who, text, kind='', ms=0): return {"who": who, "text": text, "kind": kind, "ms": ms}

def nar(text, maxlen=88): return [L('', t, 'nar') for t in split(text, maxlen)]

def say(who, text, act=None, maxlen=88):
    ch = split(text, maxlen)
    ch[0] = '“' + ch[0]; ch[-1] = ch[-1] + '”'
    if act: ch[0] = '(' + act + ')\n' + ch[0]
    return [L(who, t) for t in ch]

def ui(text): return [L('', text, 'ai')]

def cut(id, desc, lines, **kw):
    c = {"id": id, "src": "", "desc": desc, "lead": 0, "right": False, "profile": None, "lines": lines}
    c.update(kw); return c

def opt(label, sayt): return {"label": label, "say": sayt}

def ending(id, name, rule, body, quote=None):
    lines = nar(body)
    if quote: lines.append(L('', '“' + quote + '”', 'hook'))
    return {"id": id, "name": name, "rule": rule, "src": "", "desc": '엔딩 ' + id + ' · ' + name + ' (이미지 자리)', "lead": 0, "right": False, "profile": None, "lines": lines}

